"""The slides of the OpenApi video. assemble.py calls slide() for each step of a "slide" clip.

Everything visual comes from brand.py, so the slides look like those of every other Orchard Core video.
"""
from PIL import ImageDraw

# brand.py is in the skill's scripts folder; assemble.py puts it on the path.
from brand import GREEN, TEXT, W, bullets, draw_code, font, slide_base

TYPES = {"MyFeatureController", "ControllerBase", "MyDataDto", "IActionResult", "Task", "StatusCodes",
         "GetEndpointClient", "CancellationToken"}

ENDPOINTS = [
    ("1", "Your endpoints", "Controllers and minimal API endpoints of the enabled features"),
    ("2", "An OpenAPI document", "Built from those endpoints, and served as JSON"),
    ("3", "Other tools", "Anything that reads OpenAPI can use the same document"),
]

FEATURES = [
    ("1", "OpenApi", "Builds and serves the OpenAPI document"),
    ("2", "OpenApi Swagger UI", "Interactive: sends requests from the page"),
    ("3", "OpenApi ReDoc UI", "Read-only documentation"),
    ("4", "OpenApi Scalar UI", "An API reference that also sends requests"),
]

ADDRESSES = [
    ("1", "Swagger UI", "Interactive API explorer at /swagger"),
    ("2", "ReDoc", "Read-only API documentation at /redoc"),
    ("3", "Scalar", "API reference at /scalar/v1"),
]

ACCESS = [
    ("1", "Not signed in", "Redirected to the admin"),
    ("2", "Signed in, without the permission", "A 403 Forbidden response"),
    ("3", "ViewOpenApiContent", "Granted to Administrators by default; ManageOpenApi implies it"),
]

TOKENS = [
    ("1", "Bearer tokens only", "Endpoints on the Api scheme accept bearer tokens, not cookies"),
    ("2", "Swagger UI and Scalar", "Authorization code flow with PKCE, on the same tenant"),
    ("3", "ReDoc", "Read-only: it needs no token"),
]

TOKEN_CARE = [
    ("1", "In memory only", "The token never touches web storage"),
    ("2", "Same origin only", "Attached to requests whose path contains /api/"),
    ("3", "Renewed silently", "The same way, before the token expires"),
]

# openapi-pkce.recipe.json of the module, without the settings steps.
RECIPE = """
{
  "name": "OpenApiPkce",
  "steps": [
    {
      "name": "feature",
      "enable": [
        "OrchardCore.OpenApi",
        "OrchardCore.OpenId.Management",
        "OrchardCore.OpenId.Server",
        "OrchardCore.OpenId.Validation"
      ]
    },
    // ...
    {
      "name": "OpenIdApplication",
      "ClientId": "openapi",
      "Type": "public",
      "RequireProofKeyForCodeExchange": true,
      "RedirectUris": "https://localhost:5001/OrchardCore.OpenApi/openapi-oidc-silent.html"
    }
  ]
}
"""

# The example controller of the documentation.
CONTROLLER = """
[ApiController]
[Route("api/dashboard/myfeature")]
[Authorize(AuthenticationSchemes = "Api")]
public sealed class MyFeatureController : ControllerBase
{
    [HttpGet]
    [ProducesResponseType(typeof(MyDataDto), StatusCodes.Status200OK)]
    public async Task<IActionResult> GetDataAsync()
    {
        // ...
    }
}
"""

# GetEndpoint.cs of the Contents module.
MINIMAL = """
builder.MapGet("api/content/{contentItemId}", HandleAsync)
    .WithName("ApiGetContentItem")
    .AllowAnonymous()
    .DisableAntiforgery();
"""

# OpenApiClient.cs, generated by NSwag from the schema.
CLIENT = """
public partial class GetEndpointClient
{
    // ...
    public virtual System.Threading.Tasks.Task ApiGetContentItemAsync(string contentItemId)
    {
        return ApiGetContentItemAsync(contentItemId, System.Threading.CancellationToken.None);
    }
}
"""


def dotted(image, lines, top, left=110, size=30, step=58):
    """Plain lines of text, each with a green dot, under a code panel."""
    draw = ImageDraw.Draw(image)
    y = top
    for line in lines:
        draw.ellipse((left, y - 7, left + 14, y + 7), fill=GREEN)
        draw.text((left + 36, y), line, font=font(size), fill=TEXT, anchor="lm")
        y += step


def slide(step_id, chapter_title, label):
    if step_id == "why-1":
        image = slide_base(chapter_title, label, "An OpenAPI document")
        bullets(image, ENDPOINTS)
        return image

    if step_id == "why-2":
        image = slide_base(chapter_title, label, "Three explorers, one feature each")
        bullets(image, FEATURES, active={1, 2, 3})
        return image

    if step_id == "why-3":
        image = slide_base(chapter_title, label, "Where to find them")
        bullets(image, ADDRESSES)
        return image

    if step_id == "access-1":
        image = slide_base(chapter_title, label, "Who can open the explorers")
        bullets(image, ACCESS)
        return image

    if step_id == "access-2":
        image = slide_base(chapter_title, label, "Bearer tokens, acquired silently")
        bullets(image, TOKENS)
        return image

    if step_id == "access-3":
        image = slide_base(chapter_title, label, "OpenAPI Documentation — Bearer/PKCE")
        draw_code(image, (96, 240, W - 96, 1030), "openapi-pkce.recipe.json", "json", RECIPE, size=22,
                  highlight={5, 6, 7, 8, 9, 10, 11, 15, 16, 17, 18})
        return image

    if step_id == "access-4":
        image = slide_base(chapter_title, label, "Match the redirect URI to your site")
        draw_code(image, (96, 240, W - 96, 1030), "openapi-pkce.recipe.json", "json", RECIPE, size=22,
                  highlight={19})
        return image

    if step_id == "access-5":
        image = slide_base(chapter_title, label, "What happens to the token")
        bullets(image, TOKEN_CARE)
        return image

    if step_id == "own-1":
        image = slide_base(chapter_title, label, "1. Add a controller")
        draw_code(image, (96, 240, W - 96, 800), "MyFeatureController.cs", "csharp", CONTROLLER, types=TYPES,
                  size=28, highlight={1, 2, 3})
        dotted(image, [
            "ApiController and Route make the endpoint discoverable.",
            "Authorize it with the Api scheme, so it accepts bearer tokens.",
            "The explorers attach the token to routes that contain /api/.",
        ], top=880)
        return image

    if step_id == "own-2":
        image = slide_base(chapter_title, label, "2. Document the responses")
        draw_code(image, (96, 240, W - 96, 800), "MyFeatureController.cs", "csharp", CONTROLLER, types=TYPES,
                  size=28, highlight={7})
        dotted(image, [
            "One ProducesResponseType attribute for each response the action can return.",
            "The explorers list the responses with the operation.",
        ], top=880)
        return image

    if step_id == "own-3":
        image = slide_base(chapter_title, label, "3. Name the endpoint")
        draw_code(image, (96, 240, W - 96, 500), "GetEndpoint.cs", "csharp", MINIMAL, types=TYPES, size=24)
        draw_code(image, (96, 540, W - 96, 890), "OpenApiClient.cs (generated by NSwag)", "csharp", CLIENT,
                  types=TYPES, size=22)
        dotted(image, [
            "The name of the endpoint is the name of the method in the generated C# client.",
            "On a controller action, the EndpointName attribute sets it.",
        ], top=950, step=56)
        return image

    raise SystemExit(f"No slide for {step_id}")

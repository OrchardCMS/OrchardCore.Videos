"""The slides of the OpenID Connect Keys as Secrets video. assemble.py calls slide() for each step of a "slide" clip.

Everything visual comes from brand.py, so the slides look like those of every other Orchard Core video.
"""
# brand.py is in the skill's scripts folder; assemble.py puts it on the path.
from brand import bullets, slide_base

# What the server does without the feature: why-1 and why-2.
MANAGED = [
    ("1", "Generated by the server", "A signing and an encryption certificate, created for the site."),
    ("2", "Saved as files", "In the data folder of the site, on the server that runs it."),
    ("3", "Not shared between servers", "A server that finds no such files generates certificates of its own."),
]

# What the feature changes: why-3.
SECRETS = [
    ("check", "Encrypted", "Each secret is encrypted before it is saved."),
    ("check", "Listed in one place", "The Secrets page lists them, under Tools, Security."),
    ("check", "Kept in a secret store", "The database by default."),
    ("check", "Shared through the store", "Servers that share the database and the Data Protection keys."),
]

# What happens to a certificate that is already selected: carry-1.
CARRY = [
    ("1", "A certificate is selected", "The server settings name a signing or an encryption certificate."),
    ("2", "X.509 Certificate secret", "Enabling the feature saves a secret that references the certificate."),
    ("3", "Selected in the card", "The secret is chosen under RSA Keys from Secrets."),
]

# What stays in use: carry-2.
FALLBACK = [
    ("1", "Nothing selected", "A list left on None keeps the server on its certificates."),
    ("2", "A secret that cannot be loaded", "The server keeps its certificates and records the problem in its log."),
]


def slide(step_id, chapter_title, label):
    if step_id == "why-1":
        image = slide_base(chapter_title, label, "The default: managed certificates")
        bullets(image, MANAGED, active={0, 1})
        return image
    if step_id == "why-2":
        image = slide_base(chapter_title, label, "The default: managed certificates")
        bullets(image, MANAGED, active={2})
        return image
    if step_id == "why-3":
        image = slide_base(chapter_title, label, "The feature: keys as secrets")
        bullets(image, SECRETS)
        return image
    if step_id == "carry-1":
        image = slide_base(chapter_title, label, "A certificate that is already selected")
        bullets(image, CARRY)
        return image
    if step_id == "carry-2":
        image = slide_base(chapter_title, label, "What stays in use")
        bullets(image, FALLBACK)
        return image
    raise SystemExit("No slide for " + step_id)
